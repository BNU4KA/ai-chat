import type {z, DocumentBlock, conversationSchema, messageSchema, runSchema, modelSchema, fileSchema, credentialSchema, profileSchema, integrationSchema} from '@ai-chat/contracts';
export type Conversation = z.infer<typeof conversationSchema>;
export type Message = z.infer<typeof messageSchema>;
export type Run = z.infer<typeof runSchema>;
export type Model = z.infer<typeof modelSchema>;
export type FileRecord = z.infer<typeof fileSchema>;
export type Credential = z.infer<typeof credentialSchema>;
export type Profile = z.infer<typeof profileSchema>;
export type Integration = z.infer<typeof integrationSchema>;
export type Approval = {id: string; run_id: string; tool_call_id: string; tool_name: string; args_hash: string; arguments: Record<string,unknown>; structured_preview: Record<string, unknown>; status: string; expires_at: string};
export type ToolCall = {id: string; name: string; status: string; arguments: Record<string, unknown>; safe_result?: unknown};
export type Source = {citation_id: string; kind: string; title: string; url?: string; file_id?: string; document_id?:string; page?: number; section?: string;excerpt?:string;retrieved_at?:string};
export type AgentQuestionItem = {
  id: string;
  run_id: string;
  tool_call_id: string;
  questions: {
    id: string;
    text: string;
    allow_custom: boolean;
    options: { label: string; description?: string }[];
  }[];
  status: string;
  expires_at: string;
};
export type Snapshot = {run: Run; assistant_message: Message; tool_calls: ToolCall[]; approvals: Approval[]; questions?: AgentQuestionItem[]; sources: Source[]};
export type Capabilities = {tools: Record<'web'|'files'|'gmail'|'calendar', string>; limits: {file_bytes: number}};
export type DocumentDraft = {
  id: string;
  conversation_id: string;
  assistant_message_id: string | null;
  format: 'docx' | 'pdf';
  title: string;
  content: { blocks: DocumentBlock[] };
  status: 'draft' | 'created';
  file_id: string | null;
  version: number;
  created_at: string;
  updated_at: string;
};
